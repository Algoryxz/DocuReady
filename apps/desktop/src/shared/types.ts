/**
 * DocuReady Desktop - Shared TypeScript contracts and types
 */

export interface EngineHealth {
  ok: boolean;
  sidecar: string;
  protocol: number;
  engineVersion: string;
  pythonVersion: string;
  pdfBackend: string;
  ocrAvailable: boolean;
  ocrLanguages?: string[];
  ocrSource?: string;
  isBundled?: boolean;
  ocrError?: string;
  tesseractVersion?: string;
  tesseractPath?: string;
  status: "healthy" | "unhealthy" | "error";
  error?: string;
}

export interface DiagnosticReport {
  timestamp: string;
  appVersion: string;
  platform: string;
  arch: string;
  isPackaged: boolean;
  sidecarType: "packaged_binary" | "python_script";
  protocolVersion: number;
  engineVersion: string;
  pythonVersion: string;
  pdfBackend: string;
  ocrAvailable: boolean;
  ocrLanguages: string[];
  ocrSource?: string;
  isBundled?: boolean;
  ocrError?: string;
  tesseractVersion?: string;
  tesseractPath?: string;
  workspaceHealth: {
    status: "healthy" | "degraded" | "error";
    staleWorkspacesCleaned: number;
    activeWorkspacesCount: number;
  };
  resourceStatus: {
    sidecarExecutableFound: boolean;
    tesseractFound: boolean;
  };
}

export type SupportedMimeType = "application/pdf" | "image/png" | "image/jpeg";
export type SupportedFileType = "pdf" | "png" | "jpeg";

export interface DocumentDescriptor {
  id: string; // opaque ID generated by main process
  name: string; // sanitized filename, e.g. "application_form.pdf"
  size: number; // in bytes
  mimeType: SupportedMimeType;
  fileType: SupportedFileType;
}

export interface CreatePacketOptions {
  schemeId?: string;
  asOf?: string; // ISO date YYYY-MM-DD
  documentIds: string[];
}

export interface PacketDescriptor {
  packetId: string;
  schemeId: string;
  asOf: string;
  documentCount: number;
  createdAt: string;
}

export type AuditJobStatus =
  | "idle"
  | "staged"
  | "running"
  | "completed"
  | "failed"
  | "cancelled";

export interface AuditProgress {
  jobId: string;
  stage: string;
  completed: number;
  total: number;
  percent: number;
}

export interface EvidenceProvenanceDTO {
  document_type: string;
  file_name: string;
  page_number: number;
  bounding_box: [number, number, number, number] | null;
  raw_snippet: string;
  extracted_field: string;
  extraction_method: string;
  ocr_confidence: number | null;
}

export interface NormalizedEvidenceItem {
  id: string; // unique item id e.g. `${ruleId}-${evidenceIdx}`
  ruleId: string;
  ruleName: string;
  ruleStatus: string;
  severity: string;
  field: string;
  documentType: string;
  fileName: string;
  pageNumber: number;
  boundingBox: [number, number, number, number] | null;
  rawSnippet: string;
  extractedField: string;
  extractionMethod: string;
  ocrConfidence: number | null;
  hasProvenance: boolean;
  matchGrade?: string;
  reasonCode?: string;
  remediation?: string;
  statutoryReference?: string;
}

export interface RedactedFinding {
  rule_id: string;
  rule_name: string;
  status: "PASS" | "FAIL" | "WARN" | "MANUAL_REVIEW" | "MISSING" | string;
  severity: string;
  penalty: number;
  field: string;
  documents_involved: string[];
  message?: string;
  evidence?: EvidenceProvenanceDTO[];
  remediation?: string;
  statutory_reference?: string;
  reason_code?: string;
  match_grade?: string;
  evidence_details?: Array<{
    field?: string;
    document_type?: string;
    page_number?: number;
    bounding_box?: [number, number, number, number];
    evidence_state?: string;
  }>;
}

export interface DocumentFieldSummary {
  field: string;
  evidence_state: string;
  page: number | null;
  bounding_box: [number, number, number, number] | null;
  extraction_method: string;
}

export interface ExtractedDocumentSummary {
  document_type: string;
  page_count: number;
  extraction_method: string;
  fields: DocumentFieldSummary[];
}

export interface RedactedAuditResult {
  packet_id: string;
  scheme_name: string;
  readiness_score: number;
  overall_status: string;
  findings: RedactedFinding[];
  summary_counts: Record<string, number>;
  execution_time_ms?: number;
  timestamp?: string;
  as_of?: string;
  documents?: ExtractedDocumentSummary[];
}

export interface AuditStatusResponse {
  jobId: string;
  packetId: string;
  status: AuditJobStatus;
  progress?: AuditProgress;
  result?: RedactedAuditResult;
  error?: {
    code: string;
    message: string;
  };
}

export interface ExportReportOptions {
  packetId: string;
  format: "json" | "markdown";
}

export interface ExportReportResult {
  ok: boolean;
  cancelled?: boolean;
  filePath?: string;
  error?: string;
}

export interface ClearSessionResult {
  ok: boolean;
  cleanedWorkspaces: number;
}

export interface DocuReadyBridge {
  readonly platform: string;
  readonly version: string;
  getEngineHealth(): Promise<EngineHealth>;
  selectDocuments(): Promise<DocumentDescriptor[]>;
  createPacket(options: CreatePacketOptions): Promise<PacketDescriptor>;
  startAudit(packetId: string): Promise<AuditStatusResponse>;
  cancelAudit(packetId: string): Promise<AuditStatusResponse>;
  getAuditStatus(packetId: string): Promise<AuditStatusResponse>;
  exportReport(options: ExportReportOptions): Promise<ExportReportResult>;
  getDiagnosticReport(): Promise<DiagnosticReport>;
  getDocumentBinary(documentId: string): Promise<Uint8Array | null>;
  clearSession(): Promise<ClearSessionResult>;
  onAuditProgress(callback: (progress: AuditProgress) => void): () => void;
}
